# ---------------------------
def clean_jsonl(input_file, output_file):
    seen_ids = set()

    kept = 0
    removed_duplicates = 0
    removed_adult = 0
    removed_no_tags = 0

    with open(input_file, 'r', encoding='utf-8') as infile, \
         open(output_file, 'w', encoding='utf-8') as outfile:

        for line in infile:
            if not line.strip():
                continue

            try:
                data = json.loads(line)
            except json.JSONDecodeError:
                continue

            # ---------------------------
            # REMOVE ADULT
            # ---------------------------
            audiences = data.get("audiences", "")
            if isinstance(audiences, list):
                audiences_str = " ".join(audiences)
            else:
                audiences_str = str(audiences)

            if "ADULT" in audiences_str.upper():
                removed_adult += 1
                continue

            # ---------------------------
            # REMOVE DUPLICATES
            # ---------------------------
            book_id = data.get("id")
            if not book_id:
                continue

            if book_id in seen_ids:
                removed_duplicates += 1
                continue

            seen_ids.add(book_id)

            # ---------------------------
            # GENERATE TAGS
            # ---------------------------
            
            tags = clean_useless_tags(data.get("tags", []))

            # if not tags:
            #     removed_no_tags += 1
            #     continue

            data["tags"] = tags
            # Optional: remove raw genres
            # data.pop("genres", None)

            # ---------------------------
            # WRITE OUTPUT
            # ---------------------------
            outfile.write(json.dumps(data, ensure_ascii=False) + "\n")
            kept += 1

    # ---------------------------
    # SUMMARY
    # ---------------------------
    print("Done!")
    print(f"Kept: {kept}")
    print(f"Removed (duplicates): {removed_duplicates}")
    print(f"Removed (adult): {removed_adult}")
    print(f"Removed (no tags): {removed_no_tags}")


