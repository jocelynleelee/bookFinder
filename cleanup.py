def clean_useless_tags(tags):
    if not tags:
        return []

    cleaned = set()

    for tag in tags:
        if not tag:
            continue

        t = tag.strip().lower()

        # remove useless exact matches
        if t in USELESS_TAGS:
            continue

        # remove very low-quality tags
        if len(t) <= 2:
            continue

        cleaned.add(t)

    return list(cleaned)
