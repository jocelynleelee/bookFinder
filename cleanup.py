def generate_tags(book):
    tags = set()

    title = (book.get("title") or "").lower()
    genres = book.get("genres") or []

    if isinstance(genres, str):
        genres = [genres]

    genres = [g.lower() for g in genres]

    # --- THEME TAGS ---
    if any(word in title for word in ["dog", "cat", "animal", "bear", "duck"]):
        tags.add("animal")

    if any(word in title for word in ["truck", "car", "bus", "train"]):
        tags.add("vehicle")

    if any(word in title for word in ["bedtime", "sleep", "goodnight", "night"]):
        tags.add("bedtime")

    if any(word in title for word in ["mom", "dad", "family", "love"]):
        tags.add("family")

    if any(word in title for word in ["food", "eat", "apple", "cake"]):
        tags.add("food")

    # --- HOLIDAY TAGS ---
    if any("easter" in g for g in genres):
        tags.add("holiday")

    if any("christmas" in g for g in genres):
        tags.add("holiday")

    # --- LEARNING TAGS ---
    if any(word in title for word in ["count", "numbers", "1 2 3"]):
        tags.add("counting")

    if any(word in title for word in ["abc", "alphabet"]):
        tags.add("alphabet")

    if any(word in title for word in ["color", "colour"]):
        tags.add("colors")

    if any(word in title for word in ["shape"]):
        tags.add("shapes")

    # --- INTERACTION TAGS ---
    if any("touch" in g for g in genres):
        tags.add("touch_and_feel")

    if any("flap" in g for g in genres):
        tags.add("lift_the_flap")

    if any(word in title for word in ["press", "sound"]):
        tags.add("interactive")

    # --- FALLBACK ---
    if not tags:
        tags.add("general")
    cleaned_tags = clean_useless_tags(tags)
    return list(cleaned_tags)


